export type Locale = 'ru' | 'en'

const catalogs: Record<Locale, Record<MessageKey, string>> = { ru, en }

export function isLocale(value: unknown): value is Locale {
  return value === 'ru' || value === 'en'
}

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'ru'
  return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'ru'
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = catalogs[locale][key] ?? catalogs.ru[key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function categoryMessage(category: string): MessageKey {
  switch (category) {
    case 'science':
      return 'catScience'
    case 'conspiracy':
      return 'catConspiracy'
    case 'tech':
      return 'catTech'
    case 'future':
      return 'catFuture'
    case 'politics':
      return 'catPolitics'
    default:
      return 'catOther'
  }
}

export function statusMessage(status: string, short = false): MessageKey {
  if (status === 'fulfilled') return short ? 'statusFulfilledShort' : 'statusFulfilled'
  if (status === 'refuted') return short ? 'statusRefutedShort' : 'statusRefuted'
  return short ? 'statusPendingShort' : 'statusPending'
}
